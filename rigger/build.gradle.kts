// The rigger: PSD in, rig out (analysis, meshes, deformers, physics, the rig IR compiler) and the project storage
// it builds on - split out of the editor app so it can compile for the iPad (Layerloom iPad plan, phase 2).
// It must not depend on the editor's UI. Kotlin Multiplatform: shared code in src/commonMain (JVM and iPad), Java-only code in src/main (JVM).
plugins {
	kotlin("multiplatform")
	kotlin("plugin.serialization")
}

// The iPad has no ResourceBundle: the translations (src/main/resources/i18n) are embedded as Kotlin
// text for iosMain (TranslationsIos.kt), so generated part names and messages read the same on both.
val embedMessages by tasks.registering {
	val source = layout.projectDirectory.dir("src/main/resources/i18n")
	val target = layout.buildDirectory.dir("generated/i18n/kotlin")
	inputs.dir(source)
	inputs.file(layout.projectDirectory.file("src/main/resources/skinning/mhr-joints.tsv"))
	outputs.dir(target)
	doLast {
		val files = source.asFile.listFiles { f -> f.name.startsWith("Messages") && f.name.endsWith(".properties") }!!.sortedBy { it.name }
		fun literal(s: String) = buildString {
			append('"')
			for (c in s) when (c) {
				'\\' -> append("\\\\"); '"' -> append("\\\""); '$' -> append("\\$"); '\n' -> append("\\n"); '\r' -> append("\\r")
				// Surrogates as escapes: a chunk boundary may fall between the two halves of a pair.
				else -> if (c.isSurrogate()) append("\\u").append(c.code.toString(16).padStart(4, '0')) else append(c)
			}
			append('"')
		}
		val out = StringBuilder("package io.github.psd2live.i18n\n\n// Generated by the rigger's embedMessages task from src/main/resources/i18n. Do not edit.\n")
		out.append("internal object EmbeddedMessages {\n")
		val tags = files.map { it.name.removePrefix("Messages").removeSuffix(".properties").removePrefix("_").substringBefore('_').ifEmpty { "en" } }
		out.append("\tval tags: Set<String> = setOf(").append(tags.joinToString { literal(it) }).append(")\n\n")
		out.append("\tfun text(tag: String): String? = when (tag) {\n")
		for ((file, tag) in files.zip(tags)) {
			out.append("\t\t").append(literal(tag)).append(" -> buildString {\n")
			file.readText(Charsets.UTF_8).chunked(16000).forEach { out.append("\t\t\tappend(").append(literal(it)).append(")\n") }
			out.append("\t\t}\n")
		}
		out.append("\t\telse -> null\n\t}\n}\n")
		val dir = target.get().asFile.resolve("io/github/psd2live/i18n")
		dir.mkdirs()
		dir.resolve("EmbeddedMessages.kt").writeText(out.toString())
		// The text resources shared code reads (rigResourceText), by their classpath path.
		val resources = layout.projectDirectory.dir("src/main/resources").asFile
		val res = StringBuilder("package io.github.psd2live.core\n\n// Generated by the rigger's embedMessages task from src/main/resources. Do not edit.\n")
		res.append("internal object EmbeddedResources {\n\tfun text(path: String): String? = when (path) {\n")
		for (path in listOf("skinning/mhr-joints.tsv")) {
			res.append("\t\t").append(literal(path)).append(" -> buildString {\n")
			resources.resolve(path).readText(Charsets.UTF_8).chunked(16000).forEach { res.append("\t\t\tappend(").append(literal(it)).append(")\n") }
			res.append("\t\t}\n")
		}
		res.append("\t\telse -> null\n\t}\n}\n")
		val coreDir = target.get().asFile.resolve("io/github/psd2live/core")
		coreDir.mkdirs()
		coreDir.resolve("EmbeddedResources.kt").writeText(res.toString())
	}
}

kotlin {
	jvmToolchain(21)
	jvm {
		compilerOptions {
			freeCompilerArgs.add("-Xno-optimize")
		}
	}
	// The iPad: the shared rigger (src/commonMain) compiles for it; Java-only code stays in src/main.
	iosArm64()
	iosSimulatorArm64()
	sourceSets {
		val commonMain by getting {
			dependencies {
				api(project(":umamo"))
				api(project(":format-model"))
				api(project(":format-compile"))
				api(project(":targets:cubism"))
				api("org.jetbrains.kotlinx:kotlinx-serialization-json:1.11.0")
				api("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.11.0")
				implementation("com.squareup.okio:okio:3.17.0")
				implementation("org.jetbrains.kotlinx:kotlinx-datetime:0.8.0")
			}
		}
		val commonTest by getting {
			dependencies { implementation(kotlin("test")) }
		}
		// iosMain comes from the default hierarchy once the targets exist, so it is configured when it appears.
		matching { it.name == "iosMain" }.configureEach { kotlin.srcDir(embedMessages) }
		val jvmMain by getting {
			kotlin.srcDir("src/main/kotlin")
			resources.srcDir("src/main/resources")
		}
		val jvmTest by getting {
			kotlin.srcDir("src/test/kotlin")
			dependencies { implementation(kotlin("test")) }
		}
	}
}

